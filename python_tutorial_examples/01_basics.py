# Part 1: The Basics

# Your First Python Program: "Hello, World!"
print("Hello, World!")

# Variables and Data Types
# A variable named 'greeting' that stores a string
greeting = "Hello, students!"
print(greeting)

# A variable named 'age' that stores an integer
student_count = 25
print(student_count)

# A variable for pi, which is a float (a number with a decimal)
pi = 3.14159
print(pi)

# Getting User Input
name = input("What is your name? ")
print("Hello, " + name + "!")

# Basic Operations
# Addition
sum_result = 10 + 5
print(sum_result)

# Subtraction
difference = 20 - 8
print(difference)

# Multiplication
product = 7 * 6
print(product)

# Division
quotient = 50 / 10
print(quotient)

# Converting input for calculations
age_str = input("How old are you? ")
age = int(age_str)
next_year_age = age + 1
print("Next year, you will be " + str(next_year_age) + " years old.")